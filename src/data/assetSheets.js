// v5 sheet registry. v3's equivalent imports 72 tileReference files covering every
// purchased pack; this one carries five, by the art decision in
// documents/v5_scope_and_cut_list.md section 10.
//
// THE RULE, corrected 2026-09-07: nothing whose FILES may not be redistributed
// goes in the repo — which the root .gitignore enforces by extension, so no art
// is committed at all. That is a repository constraint, and this file is not the
// repository. Using a legitimately purchased pack IN THE GAME is what it was sold
// for; see documents/v3_asset_licensing.md, which states it plainly.
//
// The earlier version of this comment said "owned outright or CC0 only" and
// treated that as a rule about the build. It was over-restrictive: it confused
// "don't ship the files" with "don't use the art".
//
//   kenney         - CC0, 16px, and still the fallback the code frame-addresses
//                    directly (floor 17, wall 555, chest 302).
//   heroes         - PixelLab, owned. The three hero classes.
//   monsters       - PixelLab, owned. The enemy roster.
//   props          - PixelLab, owned. World objects.
//   realm          - PixelLab, owned. Per-realm role art for levels/themeRoles.js.
//   traps          - PixelLab, owned. Floor-hazard art for hazards/trapDefs.js.
//   containers     - MIXED, both verified. The three chest tiers + the loot sack
//                    (scope doc §10.12). 32rogues supplies the rare chest; the
//                    Fantasy RPG Tileset Pack (GameDev Market Pro Licence via the
//                    RPG Humble Bundle, verified 2026-09-22) supplies the wooden
//                    chest and the sack.
//   legendaries    - PixelLab, owned. 64px inventory icons for the 14 legendaries.
//   legendaries-floor - PixelLab, owned. Their 48px top-down floor-drop sprites,
//                    so a dropped legendary is recognisable on the ground.
//   32rogues-items - PURCHASED (Seth Boyles). Weapons, armor and items. Licence
//                    verified in full: commercial use OK, no redistribute/resell,
//                    NO generative-AI or ML input, no NFT. The first two are
//                    handled by gitignore; the third is a standing constraint on
//                    how this art may be worked on — never feed these sprites to
//                    an image model.
//   32rogues-tiles - PURCHASED (Seth Boyles), same licence as 32rogues-items.
//                    Supplies the down staircase on every floor (recipes.js
//                    roles.stairsDown), replacing the per-biome game_dev_sprites
//                    stairs at the user's request 2026-10-03. The reference is
//                    cut to the two stair entries.
//
// Still deliberately absent: 7souls, rpgitems-retro, the PURCHASED impact/fx sets
// and the tilesets/ directory. Not on principle now, but because
// documents/v3_asset_licensing.md lists their terms as UNVERIFIED. Verify before
// adding, rather than assuming.
//
// CORRECTED 2026-09-22: an earlier version of that sentence said "the impact/fx/
// trap sets", which wrongly swept in `traps` — the dungeon-trap art is ORIGINAL
// PixelLab work ("owned, free to ship" per its own _meta.license), not a
// purchased pack, so the UNVERIFIED caveat never applied to it. That one word
// cost the game every trap sprite: `assetLoader.GAME_SHEETS` has always listed
// 'traps', but with no entry here `preloadSheets` warned and skipped, `resolveArt`
// returned null, and `Trap._reveal()` bailed at its `textures.exists` guard — so
// traps fired, damaged and logged while staying permanently invisible.
// The same still applies to 'npcs', 'minerals', 'legendaries', 'cosmic' and
// '32rogues-rogues': all are requested by GAME_SHEETS and unregistered here.
//
// SPRITE_SHEETS is the game_dev_sprites pack - yours outright, 5 biomes x 6 sets plus
// shared `common` sets, generated by scripts/build_sprite_reference.mjs. It supplies
// v5's terrain. Native 32px: MapState.bind builds the layer at native size and scales
// by tileSize/native, so mixing it with the 16px kenney fallback is safe.
