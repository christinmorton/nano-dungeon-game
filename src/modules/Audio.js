// Sound. The one thing v5 ADDS to v3 rather than distilling out of it — v3
// shipped no audio at all: no load.audio, no sound files, nothing across its
// 696 files. Phaser carries its own audio, so this needs no new dependency.
//
// A module singleton like the rest of the systems layer, and deliberately one
// of the leaf-most: it imports Prefs and the generated manifest, and NOTHING
// from the game. That is what lets every other module call into it without
// thinking about import order.
//
// EVERY PATH DEGRADES TO SILENCE. The audio files are gitignored — the packs
// are licensed and enormous — so a fresh clone has the manifest but none of
// the sounds. A missing key returns null instead of throwing, exactly the way
// a missing sprite sheet renders blank rather than crashing. Restore the files
// with `node scripts/pick_audio.mjs`.
//
// The manifest is generated by that same script. Do not hand-edit it: change
// the MAPPING in scripts/pick_audio.mjs and re-run.

import prefs from './Prefs.js'
import manifest from '../data/audioManifest.json'

// Variant pools. Picking at random from several takes is what stops a repeated
// sound reading as a machine gun — footsteps fire every single hero move.
const POOLS = {
    step: ['step-stone-1', 'step-stone-2', 'step-stone-3', 'step-stone-4'],
    swing: ['melee-swing', 'melee-swing-alt'],
}

// Ability -> sound, keyed by the ability's DISPLAY name.
//
// Keyed by display name rather than derived from the class, because two of the
// twelve diverge: Blink.js is called "Riftstep" and FrostBolt.js is called
// "Rime Lance". Deriving from `constructor.name` would work in dev and then
// break in a minified build, so the mapping is written out.
const ABILITY_SOUNDS = {
    'Arc Lightning': 'ability-arclightning',
    'Barrier': 'ability-barrier',
    'Riftstep': 'ability-blink',
    'Bulwark': 'ability-bulwark',
    'Charge': 'ability-charge',
    'Cleave': 'ability-cleave',
    'Dash': 'ability-dash',
    'Rime Lance': 'ability-frostbolt',
    'Mighty Blow': 'ability-mightyblow',
    'Piercing Shot': 'ability-piercingshot',
    'Root': 'ability-root',
    'Stealth': 'ability-stealth',
    // Fifth kit ability per class (scope doc §10.6). Keyed by DISPLAY name like
    // every entry here — 'ManaBeam.js' is 'Mana Beam', and getting that wrong
    // costs no error, just a generic cast sound forever.
    'Sense': 'ability-sense',
    'Shove': 'ability-shove',
    'Mana Beam': 'ability-manabeam',
    // Ultimates (scope doc §10.5) — one per class, on the R slot.
    'The Reaving': 'ability-reaving',
    'Rain of Talons': 'ability-raintalons',
    'The Unraveling': 'ability-unraveling',
}

// Enemy -> voice, by display name. Missing entries simply stay silent.
const ENEMY_SOUNDS = {
    'Bat': 'enemy-bat',
    'Dark Sorcerer': 'enemy-sorcerer',
    'Dark Priest': 'enemy-sorcerer',
    'Ghost': 'enemy-ghost',
    'Goblin': 'enemy-goblin',
    'Goblin Archer': 'enemy-goblin',
    'Ogre': 'enemy-ogre',
    'Orc': 'enemy-orc',
    'Scorpion': 'enemy-scorpion',
    'Skeleton': 'enemy-skeleton',
    'Slime': 'enemy-slime',
    'Spider': 'enemy-spider',
}

// Floor music. Three exploration loops cycle across the ordinary floors so
// consecutive floors never share a track; the stronghold gets its own.
const FLOOR_MUSIC = ['music-floor-1', 'music-floor-2', 'music-floor-3']
const STRONGHOLD_MUSIC = 'music-stronghold'

// Two hooks can legitimately fire the same sound in one beat (a hit that also
// kills, say). Anything inside this window collapses into one playback.
const REPEAT_WINDOW_MS = 60

// Per-sound level correction, as a linear gain.
//
// The libraries are not mastered to a common level and the difference is large
// enough to make a sound simply vanish. Measured off the source WAVs:
//
//   RPG pack effects   peak  -3 dB   rms -18 dB
//   footstep pack      peak -16 dB   rms -37 dB
//
// That is roughly 19 dB, about an eighth of the perceived loudness — so the
// footsteps played correctly from the first build and were inaudible under the
// music anyway. Gain of 4 is +12 dB, and dropping the 0.5 the caller used to
// pass recovers the other 6. Web Audio gain is not clamped at 1, so this is a
// real boost rather than a no-op.
//
// Anything else that turns out too quiet belongs here rather than in a magic
// number at the call site, where the reason would be invisible.
const LEVEL_TRIM = {
    'step-stone-1': 4,
    'step-stone-2': 4,
    'step-stone-3': 4,
    'step-stone-4': 4,
}

class AudioManager {
    constructor() {
        this.scene = null
        this._music = null
        this._musicKey = null
        this._lastPlayed = new Map()
        this._reported = false
    }

    // Queue every sound in the manifest. Called from World.preload, which is
    // where the rest of the game's assets load. Phaser's cache is game-wide, so
    // sounds loaded here are available to the UI and end screens too — those
    // scenes never run before World.
    // Idempotent, so any scene that might run first can call it. Intro and World
    // both do — whichever gets there first pays for the load, and the second
    // call skips rather than making Phaser warn about duplicate keys.
    preload(scene) {
        for (const [key, file] of Object.entries(manifest)) {
            if (scene.cache.audio.exists(key)) continue
            scene.load.audio(key, `audio/${file}`)
        }
    }

    // Attach to the running scene. Also the point where a clone with no audio
    // gets told so, once, instead of failing silently — silent failure is the
    // documented failure mode of this port and it costs real diagnosis time.
    bind(scene) {
        this.scene = scene
        if (this._reported) return
        this._reported = true

        const keys = Object.keys(manifest)
        if (!keys.length) return
        const present = keys.filter(k => this._has(k)).length
        if (present === 0) {
            console.warn(
                `[audio] none of the ${keys.length} sounds loaded — the game will run silent. ` +
                `The audio files are gitignored; restore them with: node scripts/pick_audio.mjs`
            )
        } else if (present < keys.length) {
            console.warn(`[audio] ${keys.length - present} of ${keys.length} sounds failed to load.`)
        }
    }

    _has(key) {
        return !!(this.scene && this.scene.cache && this.scene.cache.audio.exists(key))
    }

    _levels() {
        const p = prefs.getPreferences()
        if (p.muted) return null
        return {
            sfx: (p.sfxVolume ?? 0.8) * (p.masterVolume ?? 1),
            music: (p.musicVolume ?? 0.5) * (p.masterVolume ?? 1),
        }
    }

    // Play a one-shot. Returns false when nothing played — a missing sound, a
    // muted game and a zero volume are all ordinary outcomes here, not errors.
    play(key, opts = {}) {
        if (!key || !this.scene || !this._has(key)) return false

        const levels = this._levels()
        if (!levels) return false
        const volume = (opts.volume ?? 1) * (LEVEL_TRIM[key] ?? 1) * levels.sfx
        if (volume <= 0) return false

        const now = Date.now()
        const last = this._lastPlayed.get(key)
        if (last && now - last < REPEAT_WINDOW_MS) return false
        this._lastPlayed.set(key, now)

        return this.scene.sound.play(key, {
            volume,
            rate: opts.rate ?? 1,
            detune: opts.detune ?? 0,
        })
    }

    // Play one at random from a named pool (see POOLS), skipping any that did
    // not load so a partial install still varies across what it does have.
    playPool(pool, opts = {}) {
        const keys = (POOLS[pool] || []).filter(k => this._has(k))
        if (!keys.length) return false
        return this.play(keys[Math.floor(Math.random() * keys.length)], opts)
    }

    playAbility(ability) {
        return this.play(ABILITY_SOUNDS[ability?.name] || 'cast')
    }

    playEnemy(entity) {
        const name = entity?.name || ''
        // Exact match first, then by SUFFIX: a titled enemy ("Savage Ogre", §10.15),
        // an elite ("Elite Orc") or a thrall ("Thrall Skeleton") is still an ogre,
        // an orc, a skeleton, and used to die in silence because the key is the
        // display name. A leader's bespoke title ("Warchief") matches nothing and
        // falls to the generic thud, which is the boss-death path anyway.
        const key = ENEMY_SOUNDS[name]
            ?? ENEMY_SOUNDS[Object.keys(ENEMY_SOUNDS).find(k => name.endsWith(k))]
        return this.play(key)
    }

    // Looping background track. Re-requesting the current track is a no-op, so
    // World.create can call this on every floor without restarting the music
    // mid-descent when two floors share a theme.
    //
    // _musicKey is the track the game WANTS playing and _music is the instance
    // actually playing it. They come apart while muted — which is what lets
    // un-muting resume the floor's track instead of leaving silence until the
    // next descent.
    playMusic(key) {
        if (!key || !this.scene) return false
        if (this._musicKey === key && this._music && this._music.isPlaying) return true

        this._stopTrack()
        this._musicKey = key
        return this._startTrack()
    }

    _startTrack() {
        const key = this._musicKey
        if (!key || !this.scene || !this._has(key)) return false
        const levels = this._levels()
        if (!levels || levels.music <= 0) return false

        this._music = this.scene.sound.add(key, { loop: true, volume: levels.music })
        this._music.play()
        return true
    }

    _stopTrack() {
        if (!this._music) return
        this._music.stop()
        this._music.destroy()
        this._music = null
    }

    stopMusic() {
        this._stopTrack()
        this._musicKey = null
    }

    // floorIndex is zero-based; isFinal marks the stronghold.
    playFloorMusic(floorIndex, isFinal = false) {
        const key = isFinal ? STRONGHOLD_MUSIC : FLOOR_MUSIC[floorIndex % FLOOR_MUSIC.length]
        return this.playMusic(key)
    }

    // Re-apply the current volume settings, so a change takes effect without
    // waiting for the next floor. Muting stops the track but keeps _musicKey,
    // so un-muting picks the same floor's music back up.
    refreshVolume() {
        const levels = this._levels()
        if (!levels || levels.music <= 0) {
            this._stopTrack()
            return
        }
        if (this._music) this._music.setVolume(levels.music)
        else this._startTrack()
    }
}

export default new AudioManager()
